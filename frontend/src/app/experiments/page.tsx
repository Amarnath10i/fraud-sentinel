"use client";

import { ArrowRight } from "lucide-react";
import Link from "next/link";
import { useQuery } from "@tanstack/react-query";
import { Card, Empty } from "@/components/ui";
import { api } from "@/lib/api";
import { REPORT_BLURBS, REPORT_ORDER } from "@/lib/reports";

export default function ExperimentsPage() {
  const reports = useQuery({ queryKey: ["reports"], queryFn: api.reports });
  const list = [...(reports.data ?? [])].sort((a, b) => REPORT_ORDER.indexOf(a.name) - REPORT_ORDER.indexOf(b.name));
  return (
    <div className="grid gap-4">
      <div>
        <h1 className="text-[20px] font-semibold tracking-tight">Experiments</h1>
        <p className="mt-1 max-w-[90ch] text-[13px] text-ink-2">
          Every result in the project is generated by code (<code>uv run sentinel &lt;command&gt;</code>) and written to{" "}
          <code>reports/</code>. Intervals are 95% card-level cluster bootstrap; the test period is never used for any
          choice.
        </p>
      </div>
      {list.length ? (
        <div className="grid gap-3 md:grid-cols-2">
          {list.map((r) => (
            <Link key={r.name} href={`/experiment?name=${r.name}`} className="group">
              <Card className="h-full transition-colors group-hover:border-accent">
                <div className="flex items-start justify-between gap-3">
                  <div>
                    <h2 className="text-[14px] font-semibold">{r.title}</h2>
                    <p className="mt-1 text-[12.5px] text-ink-2">{REPORT_BLURBS[r.name] ?? ""}</p>
                  </div>
                  <ArrowRight size={16} className="mt-0.5 shrink-0 text-muted group-hover:text-ink" />
                </div>
              </Card>
            </Link>
          ))}
        </div>
      ) : (
        <Card>
          <Empty>{reports.error ? "Cannot load reports." : "Loading…"}</Empty>
        </Card>
      )}
    </div>
  );
}
